#!/usr/bin/env python3
"""Generate item_index.go from data/items.json.

The checksum for each item is the FNV-1a 64-bit hash of "id:name:qty".
Run from the repository root:

    python3 gen/gen_index.py

item_index.go is overwritten in full; never edit it by hand.
"""

import json
import pathlib

FNV_OFFSET = 14695981039346656037
FNV_PRIME = 1099511628211
MASK = (1 << 64) - 1

HEADER = """// Code generated by gen/gen_index.py; DO NOT EDIT.

package ledger

// ItemIndex maps an item id to the FNV-1a 64 checksum of "id:name:qty",
// derived from data/items.json.
var ItemIndex = map[string]uint64{
"""


def fnv1a64(text):
    h = FNV_OFFSET
    for byte in text.encode("utf-8"):
        h ^= byte
        h = (h * FNV_PRIME) & MASK
    return h


def main():
    root = pathlib.Path(__file__).resolve().parent.parent
    items = json.loads((root / "data" / "items.json").read_text())

    lines = [HEADER]
    for item in items:
        payload = "{}:{}:{}".format(item["id"], item["name"], item["qty"])
        lines.append('\t"{}": {},\n'.format(item["id"], fnv1a64(payload)))
    lines.append("}\n")

    (root / "item_index.go").write_text("".join(lines))
    print("wrote item_index.go with {} entries".format(len(items)))


if __name__ == "__main__":
    main()
